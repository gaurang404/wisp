import Foundation

enum DocsExport {
    static let mask = "•••"

    /// Markdown API documentation for a set of saved requests, grouped by folder (folder headings in order of first appearance, then requests).
    /// Each request: "### METHOD name", URL in code, its `docs` markdown (if any), params table (enabled ones), headers table (mask Authorization/api-key-like values as "•••"), auth summary (type only, never secrets), body example in ```json fence, and an example cURL (secrets masked) — curl via HTTPClient.build with `vars` then Curl.export (fall back gracefully if build fails, e.g. unresolved URL).
    /// Starts with "# title", a generated-on line, and a table of contents with anchors.
    static func markdown(title: String, requests: [RequestSpec], vars: [String: String]) -> String {
        var folders: [(name: String, items: [RequestSpec])] = []
        for r in requests {
            let name = r.folder.trimmingCharacters(in: .whitespaces).isEmpty ? "General" : r.folder
            if let i = folders.firstIndex(where: { $0.name == name }) { folders[i].items.append(r) }
            else { folders.append((name, [r])) }
        }

        var slugs = Slugger()
        _ = slugs.slug(title)
        _ = slugs.slug("Contents")
        var toc: [String] = []
        var sections: [String] = []
        for f in folders {
            toc.append("- [\(f.name)](#\(slugs.slug(f.name)))")
            sections.append("## \(f.name)")
            for r in f.items {
                let heading = "\(r.method.rawValue) \(r.displayName)"
                toc.append("  - [\(heading)](#\(slugs.slug(heading)))")
                sections.append(section(r, heading: heading, vars: vars))
            }
        }

        let date = DateFormatter()
        date.locale = Locale(identifier: "en_US_POSIX")
        date.dateFormat = "yyyy-MM-dd"
        let head = ["# \(title)", "_Generated by Wisp on \(date.string(from: Date()))._", "## Contents", toc.joined(separator: "\n")]
        return (head + sections).joined(separator: "\n\n") + "\n"
    }

    private static func section(_ r: RequestSpec, heading: String, vars: [String: String]) -> String {
        var out = ["### \(heading)", "`\(r.url)`"]
        let docs = r.docs.trimmingCharacters(in: .whitespacesAndNewlines)
        if !docs.isEmpty { out.append(docs) }

        let params = r.params.filter { $0.enabled && !$0.key.isEmpty }
        if !params.isEmpty { out.append("**Query parameters**\n\n" + table(params)) }
        let headers = r.headers.filter { $0.enabled && !$0.key.isEmpty }
        if !headers.isEmpty { out.append("**Headers**\n\n" + table(headers)) }
        if r.auth.kind != .none { out.append("**Auth:** " + authSummary(r.auth)) }

        switch r.bodyKind {
        case .none: break
        case .json: out.append("**Body**\n\n```json\n\(JSONFormat.pretty(r.body) ?? r.body)\n```")
        case .text: out.append("**Body**\n\n```text\n\(r.body)\n```")
        case .graphql:
            out.append("**GraphQL**\n\n```graphql\n\(r.body)\n```")
            if !r.graphQLVariables.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                out.append("**Variables**\n\n```json\n\(JSONFormat.pretty(r.graphQLVariables) ?? r.graphQLVariables)\n```")
            }
        case .form:
            let fields = r.form.filter { $0.enabled && !$0.key.isEmpty }
            if !fields.isEmpty { out.append("**Form body**\n\n" + table(fields)) }
        }

        // Secret-looking env vars never reach the example; auth headers/query are masked after building.
        let safeVars = vars.reduce(into: [String: String]()) { $0[$1.key] = isSecret($1.key) ? mask : $1.value }
        if let req = try? HTTPClient.build(r, vars: safeVars) {
            out.append("**Example**\n\n```bash\n\(CodeGen.generate(masked(req, r.auth), language: .curl))\n```")
        } else {
            out.append("_Example unavailable: the URL doesn't resolve with the current environment._")
        }
        return out.joined(separator: "\n\n")
    }

    private static func authSummary(_ a: Auth) -> String {
        switch a.kind {
        case .apiKey: return "API Key (\(a.apiKeyIn.rawValue.lowercased()) `\(a.apiKeyName)`)"
        case .oauth2: return "OAuth 2 (\(a.oauth.grant.rawValue))"
        default: return a.kind.rawValue
        }
    }

    private static func masked(_ req: URLRequest, _ auth: Auth) -> URLRequest {
        var r = req
        let apiKey = auth.kind == .apiKey ? auth.apiKeyName.lowercased() : nil
        for (k, v) in req.allHTTPHeaderFields ?? [:] where isSecret(k) || k.lowercased() == apiKey {
            r.setValue(maskValue(k, v), forHTTPHeaderField: k)
        }
        if let url = req.url, var c = URLComponents(url: url, resolvingAgainstBaseURL: false), let items = c.queryItems {
            c.queryItems = items.map { isSecret($0.name) || $0.name.lowercased() == apiKey ? URLQueryItem(name: $0.name, value: mask) : $0 }
            r.url = c.url ?? url
        }
        return r
    }

    private static func table(_ rows: [KeyValue]) -> String {
        func cell(_ s: String) -> String {
            s.replacingOccurrences(of: "|", with: "\\|").replacingOccurrences(of: "\n", with: " ")
        }
        let body = rows.map { "| `\(cell($0.key))` | \(cell(maskValue($0.key, $0.value))) |" }
        return (["| Name | Value |", "| --- | --- |"] + body).joined(separator: "\n")
    }

    /// Keeps the auth scheme ("Bearer •••") so the docs still say what's expected.
    private static func maskValue(_ key: String, _ value: String) -> String {
        guard isSecret(key), !value.isEmpty else { return value }
        if key.lowercased().hasSuffix("authorization"), let sp = value.firstIndex(of: " ") {
            return value[..<sp] + " " + mask
        }
        return mask
    }

    static func isSecret(_ key: String) -> Bool {
        let k = key.lowercased()
        return ["authorization", "cookie", "key", "token", "secret", "password", "passwd", "signature", "session"]
            .contains { k.contains($0) }
    }
}

/// GitHub-style heading anchors, de-duplicated with -1, -2 … suffixes.
private struct Slugger {
    private var seen: [String: Int] = [:]

    mutating func slug(_ s: String) -> String {
        let base = String(s.lowercased().unicodeScalars.compactMap { u -> Character? in
            if u == " " { return "-" }
            let c = Character(u)
            return c.isLetter || c.isNumber || c == "-" || c == "_" ? c : nil
        })
        let n = seen[base, default: 0]
        seen[base] = n + 1
        return n == 0 ? base : "\(base)-\(n)"
    }
}
